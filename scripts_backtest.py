from __future__ import annotations

import pandas as pd

from config import Config
from data_collector import MT5DataCollector
from backtester import Backtester
from strategy_engine import StrategyEngine
from risk_manager import RiskManager


def main():
    config = Config()

    data_collector = MT5DataCollector(config)
    if not data_collector.connect():
        raise SystemExit("Failed to connect to MT5")

    try:
        from ai_predictor import AIPredictor
        from smc_detector import SMCDetector
        from liquidity_scanner import LiquidityScanner

        ai_predictor = AIPredictor(config)
        ai_predictor.data_collector = data_collector
        smc_detector = SMCDetector()
        liquidity_scanner = LiquidityScanner(config)
        strategy_engine = StrategyEngine(config, ai_predictor, smc_detector, liquidity_scanner)
        risk_manager = RiskManager(config)

        df = data_collector.get_historical_data(days_back=30)
        if df.empty:
            raise SystemExit("No historical data retrieved")
        df = data_collector.compute_features(df)

        backtester = Backtester(config, strategy_engine, risk_manager)
        results = backtester.run(df=df, initial_balance=10000)
        print(results)
    finally:
        data_collector.disconnect()


if __name__ == "__main__":
    main()

